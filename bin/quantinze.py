#!/usr/bin/env python3
"""Build and verify a reproducible TensorRT engine on the target Jetson."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import shutil
import struct
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MODEL = Path(__file__).resolve().parent / "yolo_model_kasut_farm_19August_v3.pt"
DEFAULT_OUTPUT_DIR = REPO_ROOT / "ur_ws_new/src/zed_date_detector/models"
BENCHMARK_SCRIPT = REPO_ROOT / "ur_ws_new/tools/benchmark_direct_yolo_decoder.py"


def command_output(command: list[str]) -> str:
    try:
        return subprocess.run(
            command, check=False, text=True, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, timeout=10).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return "unavailable"


def engine_metadata(path: Path) -> dict:
    with path.open("rb") as stream:
        length_bytes = stream.read(4)
        if len(length_bytes) != 4:
            raise RuntimeError("engine has no Ultralytics metadata header")
        length = struct.unpack("<I", length_bytes)[0]
        if not 0 < length < 100_000:
            raise RuntimeError(f"invalid metadata length: {length}")
        return json.loads(stream.read(length).decode("utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export an optimized, fixed-shape TensorRT engine on this Jetson")
    parser.add_argument("model", nargs="?", type=Path, default=DEFAULT_MODEL,
                        help=f"trained .pt model (default: {DEFAULT_MODEL})")
    parser.add_argument("--imgsz", type=int, default=1248,
                        help="fixed input size; 1248 preserves current accuracy")
    parser.add_argument("--workspace", type=float, default=8.0,
                        help="maximum TensorRT builder workspace in GiB")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--name", help="output stem; generated by default")
    parser.add_argument("--int8", action="store_true",
                        help="experimental INT8 instead of recommended FP16")
    parser.add_argument("--data", type=Path,
                        help="representative dataset YAML; mandatory for INT8")
    parser.add_argument("--benchmark-image", type=Path,
                        help="benchmark on this saved ZED image after export")
    parser.add_argument("--runs", type=int, default=100)
    args = parser.parse_args()

    model_path = args.model.expanduser().resolve()
    if not model_path.is_file():
        raise SystemExit(f"Model not found: {model_path}")
    if model_path.suffix.lower() != ".pt":
        raise SystemExit("Input must be the trained .pt model, not an engine")
    if args.imgsz <= 0 or args.imgsz % 32:
        raise SystemExit("--imgsz must be positive and divisible by 32")
    if args.int8 and (args.data is None or not args.data.expanduser().is_file()):
        raise SystemExit("INT8 requires --data /path/to/data.yaml")
    if not Path("/etc/nv_tegra_release").exists():
        raise SystemExit("Build the engine on the exact Jetson that will run harvesting")

    print("TARGET DEVICE")
    print(command_output(["cat", "/proc/device-tree/model"]).replace("\x00", ""))
    power_mode = command_output(["nvpmodel", "-q"])
    print(power_mode)
    if "MAXN" not in power_mode.upper():
        print("WARNING: run `sudo nvpmodel -m 0 && sudo jetson_clocks` first",
              file=sys.stderr)

    import torch
    import ultralytics
    from ultralytics import YOLO

    if not torch.cuda.is_available():
        raise SystemExit("CUDA unavailable; refusing to create a non-target engine")

    precision = "int8" if args.int8 else "fp16"
    device_name = torch.cuda.get_device_name(0).lower().replace(" ", "_")
    output_name = args.name or f"{model_path.stem}_{args.imgsz}_{precision}_{device_name}"
    if not output_name.endswith(".engine"):
        output_name += ".engine"
    output_dir = args.output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    destination = output_dir / output_name
    if destination.exists():
        raise SystemExit(
            f"Refusing to overwrite {destination}; use a different --name")

    export_args = dict(
        format="engine", device=0, imgsz=args.imgsz, batch=1,
        dynamic=False, simplify=True, nms=False, workspace=args.workspace,
        verbose=True,
    )
    if args.int8:
        export_args.update(int8=True, half=False,
                           data=str(args.data.expanduser().resolve()), fraction=1.0)
    else:
        export_args.update(half=True, int8=False)

    print("\nEXPORT SETTINGS")
    print(json.dumps(export_args, indent=2))
    exported = Path(YOLO(str(model_path)).export(**export_args)).resolve()
    if not exported.is_file():
        raise RuntimeError(f"Exported engine does not exist: {exported}")
    shutil.move(str(exported), str(destination))

    metadata = engine_metadata(destination)
    embedded = metadata.get("args", {})
    checks = {
        "batch": metadata.get("batch") == 1,
        "imgsz": metadata.get("imgsz") == [args.imgsz, args.imgsz],
        "dynamic": embedded.get("dynamic") is False,
        "half": embedded.get("half") is (not args.int8),
        "int8": embedded.get("int8") is args.int8,
        "nms": embedded.get("nms") is False,
    }
    if not all(checks.values()):
        raise RuntimeError(f"Metadata verification failed: {checks}")

    manifest = {
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "source_model": str(model_path),
        "source_sha256": sha256(model_path),
        "engine": str(destination),
        "engine_sha256": sha256(destination),
        "engine_bytes": destination.stat().st_size,
        "device": torch.cuda.get_device_name(0),
        "compute_capability": list(torch.cuda.get_device_capability(0)),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "torch": torch.__version__,
        "cuda": torch.version.cuda,
        "ultralytics": ultralytics.__version__,
        "tensorrt": command_output(
            [sys.executable, "-c", "import tensorrt as t; print(t.__version__)"]),
        "nvpmodel": power_mode,
        "export_settings": export_args,
        "embedded_metadata": metadata,
        "verification": checks,
    }
    manifest_path = destination.with_suffix(".build.json")
    manifest_path.write_text(json.dumps(manifest, indent=2, default=str) + "\n")

    print("\nVERIFIED ENGINE")
    print(f"  engine:    {destination}")
    print(f"  manifest:  {manifest_path}")
    print(f"  sha256:    {manifest['engine_sha256']}")
    print(f"  precision: {precision.upper()}  imgsz: {args.imgsz}  batch: 1")

    if args.benchmark_image:
        image = args.benchmark_image.expanduser().resolve()
        if not image.is_file():
            raise SystemExit(f"Benchmark image not found: {image}")
        print("\nDIRECT-DECODER BENCHMARK")
        subprocess.run([
            sys.executable, str(BENCHMARK_SCRIPT), "--engine", str(destination),
            "--image", str(image), "--imgsz", str(args.imgsz),
            "--runs", str(args.runs),
        ], check=True)
    else:
        print("\nBenchmark before selecting this engine:")
        print(f"  {sys.executable} {BENCHMARK_SCRIPT} --engine {destination} "
              f"--image /path/to/zed_frame.png --imgsz {args.imgsz} --runs {args.runs}")


if __name__ == "__main__":
    main()
